//! Request parsing and intake validation.
//!
//! The request is the *only* channel through which dynamic data reaches the
//! co-process. The design rule is narrow on purpose:
//!
//! > Dynamic data appears in generated Lean **only as integer literals inside a
//! > named example theorem statement** — never as a data definition, never as an
//! > axiom, never as an identifier.
//!
//! So intake is not "parse some JSON and hope". Every field is checked against a
//! closed grammar, and a curated deny-list of token sequences is rejected even
//! when it would happen to parse, so that the honest failure is reported at the
//! boundary instead of surfacing later as a confusing Lean error.
//!
//! This module never touches the filesystem or spawns anything; it is a pure
//! function of the request text.

use serde_json::Value;

use crate::status::Status;

/// The only theorem family this build knows how to generate.
pub const THEOREM_DET3: &str = "det3";

/// Freshness bound for a single co-process run (seconds).
///
/// Requests outside this window are refused: a proof obligation that claims to
/// be meaningful hours from now is a configuration bug, not data to guess at.
const MAX_HEARTBEATS: u64 = 10_000_000;

/// Memory ceiling for a single co-process run (megabytes). The property
/// checks under `decide` are tiny; a request for gigabytes means something is
/// wrong upstream, so it is rejected rather than forwarded.
const MAX_MEMORY_MB: u64 = 8192;

/// Human-visible cap on request text. Well above any real request, low enough
/// that a runaway producer cannot turn intake into a memory problem.
pub const MAX_REQUEST_BYTES: usize = 64 * 1024;

/// Token sequences that are forbidden anywhere in the raw request text.
///
/// Kept as lowercase substrings so that `Native_Decide`, `#EVAL` and similar
/// spellings are caught too. This is a defence-in-depth check: the generator
/// emits a fixed skeleton and never copies request text into Lean, so matching
/// here cannot *cause* a rejection of a request the generator would have
/// accepted invisibly — it makes the refusal legible.
const FORBIDDEN_TOKENS: &[(&str, &str)] = &[
    // Longest-prefix-first within the `attribute` / `@[` family so the reported
    // reason points at the concrete construct.
    (
        "attribute",
        "attributes can retune kernel behaviour and are not allowed",
    ),
    (
        "@[",
        "attributes can retune kernel behaviour and are not allowed",
    ),
    (
        "native_decide",
        "`native_decide` trusts the compiler instead of the kernel",
    ),
    (
        "implemented_by",
        "`implemented_by` swaps in unverified code at runtime",
    ),
    (
        "#eval",
        "`#eval` executes code instead of proving a theorem",
    ),
    ("sorry", "`sorry` closes a goal without a proof"),
    (
        "axiom",
        "`axiom` introduces an assumption that is never checked",
    ),
    (
        "extern",
        "`extern` bypasses the kernel with an opaque definition",
    ),
    ("partial", "`partial` admits a non-terminating definition"),
    ("unsafe", "`unsafe` escapes the kernel's guarantees"),
    (
        "#print",
        "`#print` is generated by the skeleton, never supplied by a request",
    ),
    ("#check", "`#check` is not part of a proof obligation"),
    (
        "import",
        "generated sources are self-contained; imports are not allowed",
    ),
];

/// A validated `det3` request.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Det3Request {
    /// The nine matrix entries in row-major order.
    pub values: [i64; 9],
    /// Integer literals that are echoed into the example statement. Defaults to
    /// `values`; a request may override it so that a deliberately-false
    /// statement can be built (which is what `proof_failed` tests need).
    pub literals: [i64; 9],
    /// The right-hand side of the example statement, as computed by the caller.
    /// When absent, the run only reports the oracle value without claiming a
    /// theorem.
    pub expected: Option<i128>,
    /// Heartbeat budget handed to `lean -T`.
    pub heartbeats: u64,
    /// Memory budget handed to `lean -M` (megabytes).
    pub memory_mb: u64,
    /// Wall-clock cap this crate enforces around the child process (seconds).
    pub timeout_secs: u64,
}

/// Why a request was refused. Carries the machine-readable status so the
/// caller does not have to map strings back to outcomes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RequestError {
    pub status: Status,
    pub message: String,
    pub field: Option<String>,
}

impl RequestError {
    fn new(status: Status, field: Option<&str>, message: impl Into<String>) -> Self {
        RequestError {
            status,
            field: field.map(str::to_string),
            message: message.into(),
        }
    }

    fn invalid(field: &str, message: impl Into<String>) -> Self {
        RequestError::new(Status::InvalidRequest, Some(field), message)
    }
}

impl std::fmt::Display for RequestError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match &self.field {
            Some(field) => write!(f, "{}: {}", field, self.message),
            None => f.write_str(&self.message),
        }
    }
}

/// Default heartbeat budget for one `decide` obligation.
pub const DEFAULT_HEARTBEATS: u64 = 400_000;
/// Default memory budget handed to `lean -M` (megabytes).
pub const DEFAULT_MEMORY_MB: u64 = 2048;
/// Default wall-clock cap (seconds). `lean -T` is a separate, in-process budget;
/// this one also covers process startup and shutdown.
pub const DEFAULT_TIMEOUT_SECS: u64 = 120;

/// Scan raw text for forbidden tokens.
///
/// Returns `(token, why)` for the first hit, scanning in table order so the
/// reported reason is stable.
pub fn find_forbidden_token(text: &str) -> Option<(&'static str, &'static str)> {
    let lower = text.to_ascii_lowercase();
    FORBIDDEN_TOKENS
        .iter()
        .find(|(tok, _)| lower.contains(tok))
        .map(|(tok, why)| (*tok, *why))
}

/// Parse and validate a request from its JSON text.
pub fn parse_request(raw: &str) -> Result<Det3Request, RequestError> {
    if raw.len() > MAX_REQUEST_BYTES {
        return Err(RequestError::invalid(
            "$",
            format!(
                "request is {} bytes, limit is {MAX_REQUEST_BYTES}",
                raw.len()
            ),
        ));
    }
    if let Some((tok, why)) = find_forbidden_token(raw) {
        return Err(RequestError::invalid(
            "$",
            format!("request text contains forbidden token `{tok}`: {why}"),
        ));
    }
    let value: Value = serde_json::from_str(raw)
        .map_err(|e| RequestError::invalid("$", format!("request is not valid JSON: {e}")))?;
    parse_value(&value)
}

/// Validate an already-parsed JSON value.
pub fn parse_value(value: &Value) -> Result<Det3Request, RequestError> {
    let obj = value
        .as_object()
        .ok_or_else(|| RequestError::invalid("$", "request must be a JSON object"))?;

    // Unknown top-level keys are refused: a typo such as "litterals" would
    // otherwise silently fall back to the default and produce a green run for a
    // statement nobody asked about.
    const KNOWN: &[&str] = &[
        "theorem",
        "values",
        "literals",
        "expected",
        "heartbeats",
        "memory_mb",
        "timeout_secs",
    ];
    for key in obj.keys() {
        if !KNOWN.contains(&key.as_str()) {
            return Err(RequestError::invalid(
                key,
                format!("unknown request field (known: {})", KNOWN.join(", ")),
            ));
        }
    }

    let theorem = obj
        .get("theorem")
        .ok_or_else(|| RequestError::invalid("theorem", "missing required field"))?;
    let theorem = theorem
        .as_str()
        .ok_or_else(|| RequestError::invalid("theorem", "must be a string"))?;
    if theorem != THEOREM_DET3 {
        return Err(RequestError::invalid(
            "theorem",
            format!("unsupported theorem `{theorem}` (this build knows `{THEOREM_DET3}`)"),
        ));
    }

    let values = obj
        .get("values")
        .ok_or_else(|| RequestError::invalid("values", "missing required field"))?;
    let values = parse_int_array("values", values)?;

    let literals = match obj.get("literals") {
        None => values,
        Some(v) => parse_int_array("literals", v)?,
    };

    let expected = match obj.get("expected") {
        None => None,
        Some(v) => Some(i128::from(parse_int("expected", v)?)),
    };

    Ok(Det3Request {
        values,
        literals,
        expected,
        heartbeats: optional_budget(obj, "heartbeats", DEFAULT_HEARTBEATS, MAX_HEARTBEATS)?,
        memory_mb: optional_budget(obj, "memory_mb", DEFAULT_MEMORY_MB, MAX_MEMORY_MB)?,
        timeout_secs: optional_budget(obj, "timeout_secs", DEFAULT_TIMEOUT_SECS, 3600)?,
    })
}

/// Read an optional budget field, bounded to `[1, max]`.
fn optional_budget(
    obj: &serde_json::Map<String, Value>,
    field: &str,
    default: u64,
    max: u64,
) -> Result<u64, RequestError> {
    let Some(v) = obj.get(field) else {
        return Ok(default);
    };
    if v.is_null() {
        return Ok(default);
    }
    let n = match v {
        Value::Number(n) => n.as_u64(),
        // Integer strings are accepted for the numeric fields so that a shell
        // pipeline can pass budgets without re-serialising JSON.
        Value::String(s) => s.trim().parse::<u64>().ok(),
        _ => None,
    }
    .ok_or_else(|| RequestError::invalid(field, "must be a positive integer"))?;
    if n == 0 || n > max {
        return Err(RequestError::invalid(
            field,
            format!("must be in 1..={max}, got {n}"),
        ));
    }
    Ok(n)
}

/// Parse exactly nine integers from an array.
fn parse_int_array(field: &str, value: &Value) -> Result<[i64; 9], RequestError> {
    let arr = value
        .as_array()
        .ok_or_else(|| RequestError::invalid(field, "must be an array of 9 integers"))?;
    if arr.len() != 9 {
        return Err(RequestError::invalid(
            field,
            format!(
                "must contain exactly 9 integers (3x3 matrix), got {}",
                arr.len()
            ),
        ));
    }
    let mut out = [0i64; 9];
    for (i, item) in arr.iter().enumerate() {
        out[i] = parse_int(&format!("{field}[{i}]"), item)?;
    }
    Ok(out)
}

/// Parse one integer from a JSON number or an integer string.
fn parse_int(field: &str, value: &Value) -> Result<i64, RequestError> {
    let parsed = match value {
        Value::Number(n) => n.as_i64().ok_or_else(|| {
            RequestError::invalid(
                field,
                format!("{n} is outside the 64-bit integer range or is not an integer"),
            )
        })?,
        Value::String(s) => {
            let t = s.trim();
            // Optional sign, then bare decimal digits — no separators, no
            // exponent, no Unicode digits.
            let digits = t
                .strip_prefix('-')
                .or_else(|| t.strip_prefix('+'))
                .unwrap_or(t);
            if !is_decimal_digits(digits) {
                return Err(RequestError::invalid(
                    field,
                    format!("`{s}` is not a decimal integer literal"),
                ));
            }
            check_magnitude(field, digits)?;
            t.parse::<i64>()
                .map_err(|_| RequestError::invalid(field, format!("`{s}` does not fit in i64")))?
        }
        _ => {
            return Err(RequestError::invalid(
                field,
                "must be an integer or a string of decimal digits",
            ))
        }
    };
    // Both spellings go through the same magnitude bound, so a JSON number
    // cannot sidestep the check that a string would trip.
    check_magnitude(field, &parsed.unsigned_abs().to_string())?;
    Ok(parsed)
}

/// True for a non-empty run of ASCII digits. No sign, no separators, no
/// exponent, no Unicode digits.
fn is_decimal_digits(s: &str) -> bool {
    !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit())
}

/// Reject literals whose absolute value is large enough that downstream
/// integer arithmetic could overflow. `det3` over i128 stays far inside this
/// bound, but the check makes the guarantee explicit instead of incidental.
const MAX_ABS_LITERAL: u128 = 1_000_000_000_000;

fn check_magnitude(field: &str, digits: &str) -> Result<(), RequestError> {
    // Compare on the digit string itself: a 14-digit run is necessarily larger
    // than the 13-digit bound, so no parse (and no overflow question) is needed.
    let stripped = digits.trim_start_matches('0');
    let too_big = stripped.len() > 13 || {
        !stripped.is_empty() && stripped.parse::<u128>().unwrap_or(0) > MAX_ABS_LITERAL
    };
    if too_big {
        return Err(RequestError::invalid(
            field,
            format!("literal magnitude exceeds {MAX_ABS_LITERAL}"),
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ok(raw: &str) -> Det3Request {
        parse_request(raw).unwrap_or_else(|e| panic!("expected ok for {raw}: {e}"))
    }

    fn err(raw: &str) -> RequestError {
        parse_request(raw).expect_err(&format!("expected refusal for {raw}"))
    }

    #[test]
    fn milestone_request_parses() {
        let r = ok(r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10]}"#);
        assert_eq!(r.values, [1, 2, 3, 4, 5, 6, 7, 8, 10]);
        // Defaults: literals mirror values, expected absent, budgets defaulted.
        assert_eq!(r.literals, r.values);
        assert_eq!(r.expected, None);
        assert_eq!(r.heartbeats, DEFAULT_HEARTBEATS);
        assert_eq!(r.memory_mb, DEFAULT_MEMORY_MB);
        assert_eq!(r.timeout_secs, DEFAULT_TIMEOUT_SECS);
    }

    #[test]
    fn integer_strings_are_accepted_including_signs() {
        let r = ok(r#"{"theorem":"det3","values":["1","-2","3","4","5","6","7","8","10"]}"#);
        assert_eq!(r.values, [1, -2, 3, 4, 5, 6, 7, 8, 10]);
        let r = ok(r#"{"theorem":"det3","values":["+1","02","3","4","5","6","7","8","10"]}"#);
        assert_eq!(r.values, [1, 2, 3, 4, 5, 6, 7, 8, 10]);
    }

    #[test]
    fn expected_and_literals_may_be_given() {
        let r = ok(
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"literals":[9,9,9,9,9,9,9,9,9],"expected":"-3"}"#,
        );
        assert_eq!(r.literals, [9; 9]);
        assert_eq!(r.expected, Some(-3));
    }

    #[test]
    fn mixed_numbers_and_strings_are_accepted() {
        let r = ok(r#"{"theorem":"det3","values":[1,"2",3,4,5,6,7,8,"10"]}"#);
        assert_eq!(r.values, [1, 2, 3, 4, 5, 6, 7, 8, 10]);
    }

    #[test]
    fn budgets_accept_numbers_and_strings_and_are_bounded() {
        let r = ok(
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"heartbeats":"1000","memory_mb":512}"#,
        );
        assert_eq!(r.heartbeats, 1000);
        assert_eq!(r.memory_mb, 512);
        for bad in [
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"memory_mb":0}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"memory_mb":99999}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"heartbeats":-1}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"heartbeats":"lots"}"#,
        ] {
            assert_eq!(err(bad).status, Status::InvalidRequest, "{bad}");
        }
    }

    #[test]
    fn malformed_requests_are_invalid_request() {
        for bad in [
            "",
            "not json",
            "[]",
            r#"{"values":[1,2,3,4,5,6,7,8,10]}"#,
            r#"{"theorem":42,"values":[1,2,3,4,5,6,7,8,10]}"#,
            r#"{"theorem":"det4","values":[1,2,3,4,5,6,7,8,10]}"#,
            r#"{"theorem":"det3"}"#,
            r#"{"theorem":"det3","values":[1,2,3]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10,11]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,"x"]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,1.5]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,"1.5"]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,"1_000"]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8," ١٢ "]} "#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,true]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,null]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"unknown_field":1}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10000000000000]}"#,
        ] {
            assert_eq!(
                err(bad).status,
                Status::InvalidRequest,
                "should refuse: {bad}"
            );
        }
    }

    #[test]
    fn every_forbidden_token_is_refused_when_it_appears_anywhere() {
        for (tok, _why) in FORBIDDEN_TOKENS {
            // The token inside a string value, with a shape that would otherwise
            // be a perfectly valid request.
            let raw =
                format!(r#"{{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"note":"{tok}"}}"#);
            assert_eq!(
                err(&raw).status,
                Status::InvalidRequest,
                "{tok} not refused"
            );
        }
    }

    #[test]
    fn forbidden_token_detection_is_case_insensitive_and_ordered() {
        assert_eq!(
            find_forbidden_token("the hood is Native_Decide").map(|(t, _)| t),
            Some("native_decide")
        );
        assert_eq!(
            find_forbidden_token("#EVAL 1+1").map(|(t, _)| t),
            Some("#eval")
        );
        assert_eq!(
            find_forbidden_token("IMPLEMENTED_BY").map(|(t, _)| t),
            Some("implemented_by")
        );
        // `@[` and `attribute` share one reason; whichever matches first is
        // reported, so pin the behaviour rather than the ordering rule.
        assert!(matches!(
            find_forbidden_token("@[simp]").map(|(t, _)| t),
            Some("@[") | Some("attribute")
        ));
        assert_eq!(
            find_forbidden_token("attribute [simp]").map(|(t, _)| t),
            Some("attribute")
        );
        assert_eq!(find_forbidden_token("{\"theorem\":\"det3\"}"), None);
    }

    #[test]
    fn lean_code_in_the_request_is_refused() {
        let attacks = [
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"literals":[1,2,3,4,5,6,7,8,10],"x":"by native_decide"}"#,
            r##"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,10],"x":"#eval (1+1)"}"##,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,"10\naxiom cheat : False"]}"#,
            r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,"10)sorry("]}"#,
        ];
        for a in attacks {
            let e = err(a);
            assert_eq!(e.status, Status::InvalidRequest, "{a}");
            assert!(e.to_string().contains("forbidden token"), "{a}: {e}");
        }
    }

    #[test]
    fn magnitude_check_accepts_the_negative_boundary() {
        let r = ok(r#"{"theorem":"det3","values":[-1000000000000,2,3,4,5,6,7,8,10]}"#);
        assert_eq!(r.values[0], -1_000_000_000_000);
        let e = err(r#"{"theorem":"det3","values":[-1000000000001,2,3,4,5,6,7,8,10]}"#);
        assert_eq!(e.status, Status::InvalidRequest);
    }

    #[test]
    fn oversized_request_is_refused() {
        let big = "x".repeat(MAX_REQUEST_BYTES + 1);
        assert_eq!(err(&big).status, Status::InvalidRequest);
    }

    #[test]
    fn error_carries_the_field_name() {
        let e = err(r#"{"theorem":"det3","values":[1,2,3]}"#);
        assert_eq!(e.field.as_deref(), Some("values"));
        let e = err(r#"{"theorem":"det3","values":[1,2,3,4,5,6,7,8,"x"]}"#);
        assert_eq!(e.field.as_deref(), Some("values[8]"));
    }
}
